#!/bin/bash
# Fetch the Swagger UI static bundle for the headless control plane (REQ-SW-PL-054).
#
# The control plane serves Swagger UI from <web-root>/assets/swagger-ui/ when
# those files are present, and falls back to a public CDN otherwise. Vendoring
# makes /api/docs work on an air-gapped machine; it is optional.
#
# Usage:
#   ./scripts/fetch-swagger-ui.sh [output-dir]
#
# Default output dir: ./rest-web-ui   (pass it to the server as --rest-web-root)
#
# The assets are build artifacts, not source: the served directory is gitignored.
set -euo pipefail

SWAGGER_VERSION="${SWAGGER_VERSION:-5.33.1}"
OUT_DIR="${1:-rest-web-ui}"
ASSET_DIR="${OUT_DIR}/assets/swagger-ui"
PKG="swagger-ui-dist@${SWAGGER_VERSION}"

echo "Fetching ${PKG} into ${ASSET_DIR} ..."
mkdir -p "${ASSET_DIR}"

base="https://unpkg.com/${PKG}"
for file in swagger-ui.css swagger-ui-bundle.js swagger-ui-standalone-preset.js; do
    echo "  - ${file}"
    curl -fsSL "${base}/${file}" -o "${ASSET_DIR}/${file}"
done

cat > "${OUT_DIR}/README.md" <<EOF
# Control-plane web root

Generated by \`scripts/fetch-swagger-ui.sh\` (swagger-ui-dist ${SWAGGER_VERSION}).
Serve this directory with \`--rest-web-root ${OUT_DIR}\` so \`/api/docs\` uses the
local Swagger UI bundle instead of the CDN.

This directory is a build artifact and is not tracked by git.
EOF

echo "Done."
echo "Start the server with:  --rest-port 8080 --rest-web-root ${OUT_DIR}"
echo "Swagger UI:             http://localhost:8080/api/docs"
